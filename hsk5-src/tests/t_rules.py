"""General UI rules (see HANDOFF §12). Answers: after EVERY answer of EVERY question type (study units, QB, test bank, and the
screens generated by buildMix / buildRevision / buildTest / genQ):
  - an answer block (.reveal) with 🔊, Pinyin and tappable words is shown and scrolled into view,
  - the answer is spoken (unless 'Tự đọc to' is off: then nothing is spoken),
  - every answer text has a recorded clip,
  - no auto-advance, 'Tiếp →' enabled AND visible inside the viewport (fixed bar, not covered) on iPhone 390x844 and iPad 820x1180,
  - no 'Đúng!' text.
Also: audio failure shows a toast; scenes of cloze questions match their sentence.
Comic (Ghép truyện) screens: Tiếp locked until done but always visible, each placed card shows Chinese (tappable, pinyin) +
Vietnamese + 🔊 and is spoken (nothing when 'Tự đọc to' is off), a male clip exists for every sentence, no auto-advance, no 'Đúng!'."""
import asyncio, sys
from comic_util import solve_nomic, bank, frame_of, read_nomic, place_tap
from playwright.async_api import async_playwright
BASE = 'http://127.0.0.1:8765/index.html'
QTYPES = ['pick', 'mc', 'match', 'hear', 'order', 'type', 'choose', 'tf', 'spot']
START = '''(qs)=>{const i=SESSIONS.findIndex(x=>x.id===98);if(i>=0)SESSIONS.splice(i,1);SESSIONS.push({id:98,title:'t',sub:'',thumb:'cup',words:[],screens:qs.concat([{t:'wrap'}])});st.sess[98]={i:0,done:0};play(98);}'''
# every question screen the app can show
COLLECT = '''()=>{const Q=new Set(%s),out=[];const add=(src,c)=>{if(c&&Q.has(c.t))out.push({src,q:JSON.parse(JSON.stringify(c))})};
  SESSIONS.filter(s=>!s.rev&&!s.mix&&!s.test&&!s.reader).forEach(s=>(s.base||s.screens).forEach((c,i)=>add('unit '+s.id+' #'+i,c)));
  Object.entries(QB).forEach(([k,a])=>a.forEach((c,i)=>add('QB '+k+' #'+i,c)));
  TESTBANK.tf.forEach((c,i)=>add('TB tf #'+i,c)); TESTBANK.spot.forEach((c,i)=>add('TB spot #'+i,c));
  Object.keys(MEAN).filter(k=>W[k]).forEach(k=>{st.wl[k]=st.wl[k]||{t:Date.now(),box:0,due:0,last:0,rev:0,n:0};});
  SESSIONS.filter(s=>s.mix).forEach(s=>buildMix(s).forEach((c,i)=>add('mix '+s.id+' #'+i,c)));
  buildTest().forEach((c,i)=>add('test #'+i,c)); buildRevision().forEach((c,i)=>add('revision #'+i,c));
  const ks=Object.keys(MEAN).filter(k=>DICT[k]&&W[k]); ks.slice(0,3).forEach(k=>['z2m','m2z','tw'].forEach(p=>add('genQ '+p+' '+k,genQ(k,p))));
  return out}''' % (str(QTYPES).replace("'", '"'))
# solve the question on screen; wrong=True answers wrongly until the app reveals the answer
SOLVE = '''([q,wrong])=>{const $=s=>document.querySelector(s),$$=s=>[...document.querySelectorAll(s)];
  const okOpt=()=>$('.opt[data-ok="1"]'), badOpts=()=>$$('.opt[data-ok="0"]');
  if(q.t==='pick'){const b=$$('.pk');if(wrong){q.opts.forEach((o,k)=>{if(!o.ok)b[k].click()})}else b[q.opts.findIndex(o=>o.ok)].click();}
  else if(q.t==='match'){q.w.forEach((id,k)=>{$('.mw[data-id="'+id+'"]').click();if(wrong&&k===0)$('.mm:not([data-id="'+id+'"])').click();$('.mm[data-id="'+id+'"]').click();});}
  else if(q.t==='tf'){(wrong?badOpts()[0]:okOpt()).click();}
  else if(['hear','mc','choose'].includes(q.t)){if(wrong){badOpts().slice(0,2).forEach(b=>b.click())}else okOpt().click();}
  else if(q.t==='order'){const put=list=>list.forEach(c=>{const t=[...document.querySelectorAll('.obank .tile')].find(x=>x.dataset.t===c);t.click()});
    if(wrong){const r=q.chunks.slice().reverse();if(r.join('')===q.chunks.join(''))r.push(r.shift());put(r);return 'later';}put(q.chunks);}
  else if(q.t==='spot'){const t=$$('.olin .tile');if(wrong){t.filter((_,k)=>k!==q.bad).slice(0,2).forEach(b=>b.click())}else t[q.bad].click();}
  else if(q.t==='type'){if(wrong){$('.ghost').click()}else{$('.tin input').value=q.zh;$('.tin button').click();}}
  return 'ok'}'''
SOLVE2 = '''([q])=>{const r=q.chunks.slice().reverse();if(r.join('')===q.chunks.join(''))r.push(r.shift());r.forEach(c=>{const t=[...document.querySelectorAll('.obank .tile')].find(x=>x.dataset.t===c);t&&t.click()})}'''
# what the screen looks like after answering
STATE = '''([q])=>{const ans=q.t==='pick'||q.t==='order'||q.t==='type'||q.t==='tf'?[q.zh]:q.t==='mc'||q.t==='spot'?[q.full]:q.t==='hear'?[q.s]:q.t==='choose'?[q.w[0]]:q.w;
  const keys=ans.map(a=>'F:'+akey(a)), plays=window.__plays.slice(), nx=document.getElementById('next'), r=nx.getBoundingClientRect();
  const hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2), rv=document.querySelector('.reveal'), ft=document.querySelector('footer').getBoundingClientRect().top;
  const rr=rv?rv.getBoundingClientRect():null, st0=document.getElementById('stage').getBoundingClientRect().top;
  return {reveal:!!rv, hasPy:!!(rv&&rv.querySelector('.rpy')), spoke:keys.some(k=>plays.includes(k)), plays:plays.length, noclip:ans.filter(a=>!hasClip(a)),
    nextVis:r.top>=0&&r.bottom<=innerHeight&&r.height>40&&!!hit&&(hit===nx||nx.contains(hit)), nextOn:!nx.disabled, stay:SS(98).i===0,
    revVis:!!rr&&rr.top>=st0-1&&rr.top<ft-30, dung:/Đúng!|Đúng rồi/.test(document.getElementById('stage').innerText), nb:[Math.round(r.top),Math.round(r.bottom),innerHeight]}}'''

async def main():
    fails = []
    def chk(c, m):
        if not c: fails.append(m); print('FAIL', m)
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/opt/pw-browsers/chromium', args=['--no-sandbox', '--autoplay-policy=no-user-gesture-required'])
        errs = []
        async def newpage(w, hgt):
            pg = await (await b.new_context(viewport={'width': w, 'height': hgt}, has_touch=True, is_mobile=w < 800)).new_page()
            pg.on('pageerror', lambda e: errs.append(str(e)))
            await pg.goto(BASE); await pg.wait_for_timeout(500); return pg
        async def run(pg, item, wrong=False, auto=1):
            q = item['q']
            await pg.evaluate(f'st.auto={auto}'); await pg.evaluate(START, [q]); await pg.wait_for_timeout(480)
            r = await pg.evaluate(SOLVE, [q, wrong]); await pg.evaluate('window.__plays.length=0')   # only what is spoken AFTER the answer counts
            if r == 'later': await pg.wait_for_timeout(500); await pg.evaluate(SOLVE2, [q]); await pg.evaluate('window.__plays.length=0')
            await pg.wait_for_timeout(700)
            return await pg.evaluate(STATE, [q])
        def judge(tag, s, auto=1):
            chk(s['reveal'], f'{tag}: answer block after answering')
            chk(s['hasPy'], f'{tag}: answer block has Pinyin button')
            if auto: chk(s['spoke'], f'{tag}: answer spoken automatically')
            else: chk(s['plays'] == 0, f'{tag}: nothing spoken when Tự đọc to is off ({s["plays"]})')
            chk(not s['noclip'], f'{tag}: no recorded clip for {s["noclip"]}')
            chk(s['nextOn'], f'{tag}: Tiếp enabled'); chk(s['stay'], f'{tag}: no auto-advance')
            chk(s['nextVis'], f'{tag}: Tiếp visible in viewport {s["nb"]}')
            chk(s['revVis'], f'{tag}: answer block scrolled into view')
            chk(not s['dung'], f'{tag}: no "Đúng!" text')

        # 1) sweep: every question screen on iPhone size, right answer; one reveal (wrong) path per type per source kind
        pg = await newpage(390, 844)
        items = await pg.evaluate(COLLECT)
        kinds = {}
        for it in items: kinds.setdefault(it['q']['t'], 0); kinds[it['q']['t']] += 1
        print('question screens:', len(items), kinds)
        chk(set(kinds) == set(QTYPES), f'all question types covered: {sorted(kinds)}')
        seen = set()
        for it in items:
            judge(f'[phone] {it["src"]} {it["q"]["t"]}', await run(pg, it))
            kk = (it['q']['t'], it['src'].split()[0])
            if kk not in seen:
                seen.add(kk); judge(f'[phone] {it["src"]} {it["q"]["t"]} (wrong/revealed)', await run(pg, it, wrong=True))
        print('phone sweep done:', len(items), 'right +', len(seen), 'revealed')
        # 2) iPad size: one per type and source kind, right + revealed; plus 'Tự đọc to' off
        pg2 = await newpage(820, 1180); seen2 = set(); n2 = 0
        for it in items:
            kk = (it['q']['t'], it['src'].split()[0])
            if kk in seen2: continue
            seen2.add(kk); n2 += 1
            judge(f'[pad] {it["src"]} {it["q"]["t"]}', await run(pg2, it))
            judge(f'[pad] {it["src"]} {it["q"]["t"]} (revealed)', await run(pg2, it, wrong=True))
        offs = {}
        for it in items: offs.setdefault(it['q']['t'], it)
        for t, it in offs.items(): judge(f'[pad] {t} auto off', await run(pg2, it, auto=0), auto=0)
        await pg2.evaluate('st.auto=1;save()')
        print('pad checks done:', n2, 'kinds x2 +', len(offs), 'auto-off')
        # 3) Tiếp visible on every non-question screen too (story, word, read, album, predict, wrap), both sizes
        for pgx, lab in ((pg, 'phone'), (pg2, 'pad')):
            bad = await pgx.evaluate('''async()=>{const bad=[];for(const s of SESSIONS.filter(s=>!s.rev&&!s.mix&&!s.test)){const L=(s.base||s.screens);
              for(let i=0;i<L.length;i++){if(!['story','word','read','comic','album','predict'].includes(L[i].t))continue;st.sess[s.id]={i,done:0,b:i};play(s.id);await new Promise(r=>setTimeout(r,30));
              const nx=document.getElementById('next'),r=nx.getBoundingClientRect(),hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);
              if(!(r.top>=0&&r.bottom<=innerHeight&&hit&&(hit===nx||nx.contains(hit))))bad.push(s.id+'#'+i)}}home();return bad}''')
            chk(not bad, f'[{lab}] Tiếp visible on lesson screens: {bad[:10]}')
        # 4) detailed reveal checks per type: Pinyin toggles ruby, a word opens the meaning sheet, the sheet does not cover Tiếp
        for t in QTYPES:
            it = offs[t]; await run(pg, it)
            await pg.click('.reveal .rpy'); chk(await pg.evaluate("document.querySelector('.reveal .rz').classList.contains('showpy')"), f'{t}: Pinyin toggles')
            vis = await pg.evaluate("(()=>{const r=document.querySelector('.reveal .w rt');return r?getComputedStyle(r).display:'none'})()")
            chk(vis != 'none', f'{t}: pinyin visible after tapping Pinyin ({vis})')
            w = await pg.query_selector('.reveal .w')
            if w:
                await w.click(); await pg.wait_for_timeout(300)
                chk(await pg.evaluate("document.getElementById('sheet').classList.contains('open')"), f'{t}: word opens meaning sheet')
                cov = await pg.evaluate("(()=>{const nx=document.getElementById('next'),r=nx.getBoundingClientRect(),hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);return hit===nx||nx.contains(hit)})()")
                chk(cov, f'{t}: meaning sheet leaves Tiếp visible')
        # 4b) comic screens (no microphone in this browser: the fallback path), both sizes; auto on and off
        cms = await pg.evaluate("SESSIONS.filter(s=>!s.rev&&!s.mix&&!s.test).flatMap(s=>(s.base||s.screens).map((c,i)=>[s.id,i,c.t]).filter(x=>x[2]==='comic'))")
        chk(cms, 'comic screens found')
        for pgx, lab in ((pg, 'phone'), (pg2, 'pad')):
            for sid_, i, _ in cms:
                for auto in (1, 0):
                    tag = f'[{lab}] comic unit {sid_} #{i} auto {auto}'
                    await pgx.evaluate(f"st.auto={auto};st.sess[{sid_}]={{i:{i},b:{i},done:0}};play({sid_})"); await pgx.wait_for_timeout(400)
                    nx = await pgx.evaluate("(()=>{const nx=document.getElementById('next'),r=nx.getBoundingClientRect(),hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);return [nx.disabled,r.top>=0&&r.bottom<=innerHeight&&(hit===nx||nx.contains(hit))]})()")
                    chk(nx[0] and nx[1], f'{tag}: Tiếp locked but visible before done {nx}')
                    spoke = []
                    for c in await bank(pgx):
                        n = await frame_of(pgx, c); await read_nomic(pgx, c); await pgx.evaluate('window.__plays.length=0')
                        await place_tap(pgx, n); await pgx.wait_for_timeout(600)
                        spoke.append(await pgx.evaluate(f"__plays.length?(__plays.includes('M:'+akey(BOOK[{c}].zh))?1:-1):0"))
                    chk(all(x == 1 for x in spoke) if auto else all(x == 0 for x in spoke), f'{tag}: placed sentence spoken (auto {auto}): {spoke}')
                    s2 = await pgx.evaluate(f"""(()=>{{const C=SESSIONS.find(x=>x.id==={sid_}).screens[{i}],pl=[...document.querySelectorAll('.cm-pl')],nx=document.getElementById('next'),r=nx.getBoundingClientRect(),hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);
                      return {{n:pl.length,want:C.ids.length,vi:pl.every(p=>p.querySelector('.cm-v').textContent.trim().length>3),spk:pl.every(p=>p.querySelector('.spk')),w:pl.every(p=>p.querySelector('.w')),
                        clip:C.ids.filter(k=>!AUD['M|'+akey(BOOK[k].zh)]),on:!nx.disabled,vis:r.top>=0&&r.bottom<=innerHeight&&(hit===nx||nx.contains(hit)),dung:/Đúng!|Đúng rồi/.test(document.getElementById('stage').innerText),i:SS({sid_}).i}}}})()""")
                    chk(s2['n'] == s2['want'] and s2['vi'] and s2['spk'] and s2['w'], f'{tag}: every placed card shows Chinese + Vietnamese + 🔊 {s2}')
                    chk(not s2['clip'], f'{tag}: male clip for every sentence {s2["clip"]}')
                    chk(s2['on'] and s2['vis'], f'{tag}: Tiếp open and visible when done')
                    chk(not s2['dung'], f'{tag}: no "Đúng!" text')
                    await pgx.wait_for_timeout(800); chk(await pgx.evaluate(f'SS({sid_}).i') == i, f'{tag}: no auto-advance')
                    if auto and lab == 'phone':
                        await pgx.evaluate("setPy(1)"); vis = await pgx.evaluate("(()=>{const r=document.querySelector('.cm-pl .w rt');return r?getComputedStyle(r).display:'none'})()"); await pgx.evaluate("setPy(0)")
                        chk(vis != 'none', f'{tag}: pinyin over placed cards with 拼')
                        await pgx.click('.cm-pl .w'); await pgx.wait_for_timeout(300)
                        chk(await pgx.evaluate("document.getElementById('sheet').classList.contains('open')"), f'{tag}: word in a placed card opens the meaning sheet')
            await pgx.evaluate('st.auto=1;save();home()')
        print('comic checks done:', len(cms), 'screens x 2 sizes x auto on/off')
        # 5) audio failure -> toast, no crash
        await pg.goto(BASE); await pg.wait_for_timeout(300)
        r = await pg.evaluate('''async()=>{ac().resume=()=>Promise.resolve();Object.defineProperty(ac(),'state',{get:()=>'suspended'});const k=Object.keys(AUD).find(x=>!x.includes('|'));
          window.Audio=function(){this.play=()=>Promise.reject(new Error('x'));this.pause=()=>{}};const ok=await speak(k);return [ok,document.getElementById('toast').textContent]}''')
        chk(r[0] is False and 'âm thanh' in r[1], f'audio failure toast: {r}')
        # 6) scenes of the cloze questions match
        sc = await pg.evaluate("QB['如何'].filter(q=>q.t==='mc').map(q=>q.scene).concat(QB['爱护'].filter(q=>q.t==='mc').map(q=>q.scene))")
        chk('how' not in sc[:1] and 'garden' not in sc[1:], f'cloze scenes: {sc}')
        chk(not errs, f'page errors {errs[:5]}')
        await b.close()
    print('RULES', 'FAIL' if fails else 'OK', len(fails), 'failures', fails[:20])
    sys.exit(1 if fails else 0)
asyncio.run(main())
